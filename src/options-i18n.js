  function normalizeLocale(value) {
    return supportedLocales.includes(value) ? value : "zh-CN";
  }

  function interpolate(template, params) {
    return template.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/gu, (_match, key) => (
      Object.hasOwn(params, key) ? String(params[key]) : `{${key}}`
    ));
  }

  function translate(locale, key, params = {}) {
    const normalized = normalizeLocale(locale);
    const template = catalogs[normalized]?.[key] ?? catalogs["zh-CN"]?.[key] ?? key;
    if (normalized === "en" && (key === "history.count" || key === "history.searchCount")) {
      const count = Number(params.count) || 0;
      const total = Number(params.total) || 0;
      if (key === "history.count") {
        return `${count} ${count === 1 ? "record" : "records"}`;
      }
      return `Found ${count} of ${total} ${total === 1 ? "record" : "records"}`;
    }
    return interpolate(template, params);
  }

  function catalogKeys(locale) {
    return Object.keys(catalogs[normalizeLocale(locale)]).sort();
  }

  globalThis.JP_TRANSLATION_I18N = Object.freeze({
    supportedLocales,
    normalizeLocale,
    translate,
    catalogKeys
  });
